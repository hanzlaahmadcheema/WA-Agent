export type MediaDownloader = (msg: proto.IWebMessageInfo, type: 'buffer') => Promise<Buffer>;

export interface PipelineResult {
  shouldReply: boolean;
  replyText?: string;
  recipientJid?: string;
  isDuplicate?: boolean;
  isUnauthorized?: boolean;
  ignoredReason?: string;
  media?: MediaPayload;
}

const selfIdentities = new Set<string>([
  '923124706501',
  '244410113613956',
  '244410113613956@lid',
  '923124706501@s.whatsapp.net',
]);

export function registerSelfIdentity(jid?: string | null): void {
  if (!jid) return;
  const norm = normalizeJid(jid);
  selfIdentities.add(norm.jid);
  selfIdentities.add(norm.user);
  selfIdentities.add(norm.phoneNumber);
}

export function isSelfChat(jid?: string | null): boolean {
  if (!jid) return false;
  const norm = normalizeJid(jid);
  return (
    selfIdentities.has(norm.jid) ||
    selfIdentities.has(norm.user) ||
    selfIdentities.has(norm.phoneNumber)
  );
}

export function isPublicCommandText(text: string): boolean {
  const trimmed = text.trim();
  const lower = trimmed.toLowerCase();
  // Reminders
  if (
    /^remind\b/i.test(trimmed) ||
    /^\/remind\b/i.test(trimmed) ||
    /^\/reminders\b/i.test(trimmed) ||
    lower === 'reminders'
  ) {
    return true;
  }
  // Schedule / Timetable
  if (
    /^\/schedule\b/i.test(trimmed) ||
    /^\/timetable\b/i.test(trimmed) ||
    /^\/tt\b/i.test(trimmed) ||
    /^\/classes\b/i.test(trimmed) ||
    /^(schedule|timetable|tt|classes)\b/i.test(trimmed)
  ) {
    return true;
  }
  // System latency & server clock
  if (
    /^\/ping\b/i.test(trimmed) ||
    lower === 'ping' ||
    /^\/time\b/i.test(trimmed) ||
    lower === 'time'
  ) {
    return true;
  }
  // Menu shortcuts for reminders (11) and schedule (12)
  if (trimmed === '11' || trimmed === '12') {
    return true;
  }
  return false;
}

export function extractMessageText(message: proto.IMessage | null | undefined): string | null {
  if (!message) return null;

  return (
    message.conversation ||
    message.extendedTextMessage?.text ||
    message.imageMessage?.caption ||
    message.videoMessage?.caption ||
    null
  );
}

/**
 * Deterministic message processing pipeline:
 * 1. Normalize message & sender
 * 2. Filter group chats (@g.us)
 * 3. Authorize sender JID BEFORE parsing
 * 4. Deduplicate message ID
 * 5. Handle audio / image attachments
 * 6. Route command / natural conversation & generate reply
 */
export async function executeMessagePipeline(
  msg: proto.IWebMessageInfo,
  resolveAdminLid?: (phone: string) => Promise<string | undefined>,
  customDownloader?: MediaDownloader
): Promise<PipelineResult> {
  // 1. Sanity & Malformed Message Checks
  if (!msg || !msg.key) {
    return { shouldReply: false, ignoredReason: 'Malformed message (missing key)' };
  }

  // Ignore status broadcasts and outbound messages generated by the agent
  if (msg.key.remoteJid === 'status@broadcast' || isMessageSentByAgent(msg.key.id)) {
    return { shouldReply: false, ignoredReason: 'Outbound or broadcast message' };
  }

  // If fromMe: only allow if sent to self (self-chat / CLI test)
  if (msg.key.fromMe && !isSelfChat(msg.key.remoteJid)) {
    return { shouldReply: false, ignoredReason: 'Outbound message to third party' };
  }

  // 2. Ignore group chats
  if (msg.key.remoteJid?.endsWith('@g.us')) {
    return { shouldReply: false, ignoredReason: 'Group messages not supported' };
  }

  // Identify sender JID
  const senderJid = msg.key.participant || msg.key.remoteJid;
  if (!senderJid) {
    return { shouldReply: false, ignoredReason: 'Unable to determine sender JID' };
  }

  const pushName = msg.pushName || undefined;

  // 3. On-demand admin LID resolution: if sender is an unverified LID user and admin LID is not yet known
  if (senderJid.endsWith('@lid') && !isSenderAdmin(senderJid) && resolveAdminLid) {
    try {
      for (const phone of getAllAuthorizedPhones()) {
        const resolved = await resolveAdminLid(phone);
        if (resolved) {
          registerAdminLid(resolved);
        }
      }
    } catch {
      // Resolution failure falls through to authorization check
    }
  }

  // 4. Sender Registration & Authorization Resolution
  let userRecord: { user: any; isAuthorized: boolean };
  try {
    userRecord = getOrCreateUser(senderJid, pushName);
  } catch {
    return { shouldReply: false, ignoredReason: 'User registration failed' };
  }
  const isAuthorized = userRecord.isAuthorized;

  // 4. Message Deduplication Check
  const messageId = msg.key.id;
  if (messageId) {
    const isFresh = trackInboundMessage(messageId, senderJid);
    if (!isFresh) {
      return {
        shouldReply: false,
        isDuplicate: true,
        ignoredReason: `Duplicate message ID: ${messageId}`,
      };
    }
  }

  // Media downloader instance with retry capability for transient network failures
  const mediaDownloader: MediaDownloader =
    customDownloader ||
    (async (m) => {
      let lastErr: any;
      for (let attempt = 1; attempt <= 3; attempt++) {
        try {
          return await downloadMediaMessage(m, 'buffer', {});
        } catch (e: any) {
          lastErr = e;
          if (attempt < 3) {
            await new Promise((resolve) => setTimeout(resolve, 1000 * attempt));
          }
        }
      }
      throw lastErr;
    });

  // 5. Extract Text & Handle Multimodal Media (Audio Voice Notes & Images)
  let text = extractMessageText(msg.message);
  let isVoiceNote = false;

  // 5.1 Audio Voice Notes
  if (!text && msg.message?.audioMessage) {
    try {
      const audioBuffer = await mediaDownloader(msg, 'buffer');
      const mimetype = msg.message.audioMessage.mimetype || 'audio/ogg';
      const transcription = await transcribeAudio(audioBuffer, mimetype);
      if (transcription.success && transcription.text) {
        let raw = transcription.text.trim();
        // Remove leading colon if user said ":Hello"
        if (raw.startsWith(':')) {
          raw = raw.slice(1).trim();
        }
        // Normalize single-word trailing period (e.g. "Hello." -> "Hello")
        if (/^[A-Za-z0-9\s]+[.]$/.test(raw)) {
          raw = raw.slice(0, -1).trim();
        }
        text = raw;
        isVoiceNote = true;
      } else {
        return {
          shouldReply: true,
          recipientJid: msg.key.remoteJid!,
          replyText: `🎤 *Voice Note Received*\n\n⚠️ Could not transcribe audio:\n${transcription.error || 'Transcription failed.'}\n\n_Configure GROQ_API_KEY, OPENAI_API_KEY, or install whisper CLI in /etc/wa-agent/environment._`,
        };
      }
    } catch (err: any) {
      return {
        shouldReply: true,
        recipientJid: msg.key.remoteJid!,
        replyText: `🎤 *Voice Note Received*\n\n❌ Failed to download audio: ${err.message}`,
      };
    }
  }

  // 5.2 Image Attachments
  if (msg.message?.imageMessage) {
    const tmpDir = '/tmp/wa-agent-media';
    if (!fs.existsSync(tmpDir)) {
      fs.mkdirSync(tmpDir, { recursive: true });
    }
    const ext = msg.message.imageMessage.mimetype?.includes('png') ? '.png' : '.jpg';
    const imagePath = path.join(tmpDir, `attachment_${Date.now()}${ext}`);

    try {
      const imageBuffer = await mediaDownloader(msg, 'buffer');
      fs.writeFileSync(imagePath, imageBuffer);

      const rawCaption = (msg.message.imageMessage.caption || '').trim();
      const instruction = rawCaption || 'Please inspect this image and summarize or resolve any issues shown.';

      if (rawCaption.startsWith('/run ')) {
        text = `/run [Attached Image: ${imagePath}]\n${rawCaption.slice(5).trim()}`;
      } else if (rawCaption.startsWith('/')) {
        text = rawCaption;
      } else {
        text = `[Attached Image: ${imagePath}]\n${instruction}`;
      }
    } catch (err: any) {
      console.warn('[MessagePipeline] Image download error:', err.message);
      text = msg.message.imageMessage.caption || null;
    }
  }

  if (!text || !text.trim()) {
    return { shouldReply: false, ignoredReason: 'No text or supported media content' };
  }

  // 5.3 Enforce maximum message length
  if (text.length > LIMITS.MAX_MESSAGE_CHARS) {
    return {
      shouldReply: true,
      recipientJid: msg.key.remoteJid!,
      replyText: `❌ *ERR_INVALID_ARG*: Message exceeds maximum allowed size of ${LIMITS.MAX_MESSAGE_CHARS.toLocaleString()} characters.\n👉 Shorten your message.`,
    };
  }

  // 5.4 Enforce inbound message rate limit
  try {
    checkAndRecordRateLimit(senderJid, 'inbound');
  } catch (err: any) {
    if (err instanceof RateLimitedError) {
      return {
        shouldReply: true,
        recipientJid: msg.key.remoteJid!,
        replyText: err.toWhatsApp(),
      };
    }
  }

  // 5.5 Command & Natural Chat Gating
  const trimmed = text.trim();
  const lower = trimmed.toLowerCase();

  // A. Voice-to-Text Dictation Mode:
  // If the user spoke a voice note and did not speak an explicit slash command or reminder,
  // return the transcribed text directly as a clean message ("no other thing").
  if (isVoiceNote) {
    const isExplicitCommand =
      trimmed.startsWith('/') || /^\d+$/.test(trimmed) || /^remind\b/i.test(trimmed);
    if (!isExplicitCommand) {
      return {
        shouldReply: true,
        recipientJid: msg.key.remoteJid!,
        replyText: trimmed,
      };
    }
  }

  // B. Explicit echo prefix e.g. ":Hello"
  if (trimmed.startsWith(':')) {
    const echo = trimmed.slice(1).trim();
    if (echo) {
      return {
        shouldReply: true,
        recipientJid: msg.key.remoteJid!,
        replyText: echo,
      };
    }
  }

  // C. Friendly greetings: return "Hello" directly rather than dumping the full control plane menu
  if (['hello', 'hi', 'hey'].includes(lower)) {
    return {
      shouldReply: true,
      recipientJid: msg.key.remoteJid!,
      replyText: 'Hello',
    };
  }

  const isFriendlyKeyword = [
    'menu', 'help', 'start', 'status', 'chats', 'chat',
    'diff', 'push', 'jobs', 'cancel', 'stop', 'model', 'models', 'reminders',
    'schedule', 'timetable', 'tt', 'classes', 'ping', 'time'
  ].includes(lower);

  const isSchedulePrefix = /^(schedule|timetable|tt|classes)\b/i.test(trimmed);
  const isRemindPrefix = /^remind\b/i.test(trimmed);

  let isCommandOrSelection =
    trimmed.startsWith('/') ||
    /^\d+$/.test(trimmed) ||
    isFriendlyKeyword ||
    isSchedulePrefix ||
    isRemindPrefix;

  // Natural Conversation Mode check:
  // If user is authorized, CLI session is active, and an active project + session exist:
  if (!isCommandOrSelection && isAuthorized) {
    try {
      if (isCliActive(userRecord.user.id)) {
        const activeProj = getActiveProject(userRecord.user.id);
        if (activeProj) {
          const activeSess = getActiveSession(activeProj.id);
          if (activeSess) {
            isCommandOrSelection = true;
          }
        }
      }
    } catch {}
  }

  if (!isCommandOrSelection) {
    return { shouldReply: false, ignoredReason: 'Non-command text' };
  }

  // 5.6 Authorization Check: Enforce strictly for non-public commands
  if (!isAuthorized && !isPublicCommandText(trimmed)) {
    return {
      shouldReply: true,
      recipientJid: msg.key.remoteJid!,
      replyText: '🛑 *Access Denied*: Unauthorized sender.',
      isUnauthorized: true,
    };
  }

  // 6. Execute Command via Router
  const output = await processIncomingMessage(senderJid, trimmed, pushName);
  if (!output) {
    return { shouldReply: false, ignoredReason: 'Command returned empty reply' };
  }

  const replyText = typeof output === 'string' ? output : output.text;
  const media = typeof output === 'string' ? undefined : output.media;
  const isDenied = replyText.includes('🛑 *Access Denied*');

  return {
    shouldReply: true,
    recipientJid: msg.key.remoteJid!,
    replyText,
    media,
    isUnauthorized: isDenied ? true : undefined,
  };
}
